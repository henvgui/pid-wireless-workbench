"""Rebuild the embedded F407 SRAM algorithm with Arm GNU Toolchain (no hardware)."""
from pathlib import Path
import argparse, shutil, subprocess, tempfile, struct, hashlib
here=Path(__file__).resolve().parent
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check',action='store_true',help='Fail if checked-in header differs')
args=parser.parse_args()
def tool(name):
    path=shutil.which('arm-none-eabi-'+name)
    if not path:raise RuntimeError('Arm GNU Toolchain missing: '+name)
    return path
with tempfile.TemporaryDirectory(prefix='pid-ram-') as temp:
    elf=Path(temp)/'loader.elf';binary=Path(temp)/'loader.bin'
    subprocess.run([tool('gcc'),'-mcpu=cortex-m4','-mthumb','-mfloat-abi=soft','-Os','-std=c11',
                    '-ffreestanding','-fno-builtin','-fno-stack-protector','-fno-unwind-tables',
                    '-fno-asynchronous-unwind-tables','-nostdlib','-Wl,--build-id=none',
                    '-Wl,-T,'+str(here/'f407_loader.ld'),str(here/'f407_loader.c'),'-o',str(elf)],check=True)
    subprocess.run([tool('objcopy'),'-O','binary',str(elf),str(binary)],check=True)
    symbols={line.split()[2]:int(line.split()[0],16) for line in subprocess.check_output([tool('nm'),str(elf)],text=True).splitlines() if len(line.split())==3}
    raw=binary.read_bytes();data=raw+b'\xff'*((-len(raw))%4)
    assert len(data)<=2048 and symbols['ram_entry']==0x20000000
    lines=['// Generated by ram_loader/build.py; do not edit.','// SHA256 (unpadded): '+hashlib.sha256(raw).hexdigest(),
           '#pragma once','#include <cstdint>','namespace pidflash {',
           'constexpr uint32_t kRamEntry=0x%08xu,kRamBreakpoint=0x%08xu;'%(symbols['ram_entry'],symbols['ram_breakpoint']),
           'static const uint32_t kRamCode[] = {']
    words=struct.unpack('<%dI'%(len(data)//4),data)
    lines+=['  '+','.join('0x%08xu'%v for v in words[i:i+6])+',' for i in range(0,len(words),6)]
    lines+=['};','} // namespace pidflash','']
    text='\n'.join(lines);output=here.parent/'src/f407_loader_image.h'
    if args.check:
        if output.read_text(encoding='utf-8')!=text:raise SystemExit('Embedded loader header is stale')
    else:output.write_text(text,encoding='utf-8',newline='\n')
    print('F407 SRAM loader: %d bytes, entry=%#x, breakpoint=%#x'%(len(data),symbols['ram_entry'],symbols['ram_breakpoint']))
